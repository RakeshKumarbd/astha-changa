const STRINGS: Record<Lang, Strings> = { en, hi };
export type TextKey = { [K in keyof Strings]: Strings[K] extends string ? K : never }[keyof Strings];

const LANG_KEY = 'astha-changa:lang';

function loadLang(): Lang {
  try {
    const v = localStorage.getItem(LANG_KEY);
    if (v === 'en' || v === 'hi') return v;
  } catch {
    /* storage unavailable */
  }
  return navigator.language?.startsWith('hi') ? 'hi' : 'en';
}

let lang: Lang = loadLang();

export const getLang = (): Lang => lang;

export function setLang(l: Lang): void {
  lang = l;
  document.documentElement.lang = l;
  try {
    localStorage.setItem(LANG_KEY, l);
  } catch {
    /* storage unavailable */
  }
}

export function t(key: TextKey, vars: Record<string, string | number> = {}): string {
  return STRINGS[lang][key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

export const colorName = (color: number): string => STRINGS[lang].colors[color]!;
export const seatName = (position: number): string => STRINGS[lang].seatNames[position]!;
